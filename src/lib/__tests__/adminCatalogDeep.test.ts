import { describe, expect, it } from 'vitest';
import { filterCatalog } from '../adminCatalog';

describe('admin catalog deep review', () => {
  const rows = [
    { title: 'Normal Song', artist: 'Artist', album: 'Album', is_visible: true },
    { title: 'Song (AI cover)', artist: 'Uploader', album: 'Album', is_visible: true },
    { title: 'Regular', artist: 'AI Music Factory', album: 'Album', is_visible: true },
    { title: 'Regular', artist: 'Artist', album: 'Generated by Suno', is_visible: true },
  ];

  it('identifies AI slop in title, artist, and album', () => {
    const aiTracks = filterCatalog(rows, '', 'ai-review');
    expect(aiTracks.length).toBe(3);
    expect(aiTracks.map(r => r.title)).not.toContain('Normal Song');
  });

  it('combines search and filters', () => {
    const result = filterCatalog(rows, 'Factory', 'ai-review');
    expect(result.length).toBe(1);
    expect(result[0].artist).toBe('AI Music Factory');
  });
});
